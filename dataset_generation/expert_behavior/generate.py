import argparse
import os
from concurrent.futures import ThreadPoolExecutor

import jax
import jax.numpy as jnp
import numpy as np
import optax
import yaml
from craftax.craftax_env import make_craftax_env_from_name
from flax.training.train_state import TrainState
from orbax.checkpoint import PyTreeCheckpointer, CheckpointManager, CheckpointManagerOptions
from tqdm import tqdm

from dataset_generation.expert_behavior.nn import ActorCriticRNN, ScannedRNN


_SPAWN_PARAM_KEYS = (
    "spawn_cow_chance",
    "spawn_zombie_base_chance",
    "spawn_zombie_night_chance",
    "spawn_skeleton_chance",
)


def _apply_env_param_overrides(env_params, config):
    overrides = {}
    for key in _SPAWN_PARAM_KEYS:
        val = config.get(key.upper())
        if val is not None:
            overrides[key] = float(val)
    if overrides:
        env_params = env_params.replace(**overrides)
    return env_params


def make_batch_rngs(seed: int, start_ep: int, batch_i: int, batch_size: int):
    """Derive deterministic but job-unique RNGs for one generation batch.

    Large datasets are generated by sharding one logical dataset across many jobs
    with different `start_ep` values. If `start_ep` is not folded into the RNG, each
    job replays the same trajectories and only the filenames differ.
    """
    job_key = jax.random.fold_in(jax.random.PRNGKey(seed), int(start_ep))
    batch_key = jax.random.fold_in(job_key, int(batch_i))
    reset_key, step_key = jax.random.split(batch_key)
    reset_rngs = jax.random.split(reset_key, batch_size)
    return reset_rngs, step_key


def load_policy(checkpoint_path, config, env, action_dim, seed=42):
    orbax_checkpointer = PyTreeCheckpointer()
    options = CheckpointManagerOptions(max_to_keep=1, create=False)
    checkpoint_manager = CheckpointManager(
        os.path.join(os.path.abspath(checkpoint_path), "policies"),
        orbax_checkpointer,
        options,
    )
    train_num_envs = config.get("_TRAIN_NUM_ENVS", config["NUM_ENVS"])

    """Load a trained policy from a checkpoint"""
    network = ActorCriticRNN(action_dim=action_dim, config=config)

    env_params = env.default_params

    init_x = (
        jnp.zeros(
            (1, config["NUM_ENVS"], *env.observation_space(env_params).shape),
        ),
        jnp.zeros((1, config["NUM_ENVS"])),
    )
    init_hstate = ScannedRNN.initialize_carry(
        config["NUM_ENVS"], config["LAYER_SIZE"]
    )

    rng = jax.random.PRNGKey(seed)
    rng, _rng, __rng = jax.random.split(rng, 3)
    network_params = network.init(_rng, init_hstate, init_x)

    step = checkpoint_manager.latest_step()
    if step is None:
        raise FileNotFoundError(f"No checkpoints found in {checkpoint_path}")

    if config.get("ANNEAL_LR"):
        def linear_schedule(count):
            num_updates = config.get("NUM_UPDATES")
            if num_updates is None:
                num_updates = (
                    config["TOTAL_TIMESTEPS"]
                    // config["NUM_STEPS"]
                    // train_num_envs
                )
            frac = 1.0 - (
                count // (config["NUM_MINIBATCHES"] * config["UPDATE_EPOCHS"])
            ) / num_updates
            return config["LR"] * frac

        tx = optax.chain(
            optax.clip_by_global_norm(config["MAX_GRAD_NORM"]),
            optax.adam(learning_rate=linear_schedule, eps=1e-5),
        )
    else:
        tx = optax.chain(
            optax.clip_by_global_norm(config["MAX_GRAD_NORM"]),
            optax.adam(config["LR"], eps=1e-5),
        )
    train_state = TrainState.create(
        apply_fn=network.apply,
        params=network_params,
        tx=tx,
    )
    if isinstance(train_state.opt_state, tuple) and len(train_state.opt_state) >= 1:
        # Stored checkpoints use None for the first transform (clip), so mirror that
        # layout before restoring to avoid metadata mismatches.
        train_state = train_state.replace(
            opt_state=(None, *train_state.opt_state[1:])
        )

    train_state = checkpoint_manager.restore(step, items=train_state)

    return network, train_state


def generate_batch(network, train_state, env, env_params, config, rngs, max_steps, rng, init_vitals=None):
    """Generate a batch of trajectories in parallel using vmap + scan."""
    batch_size = rngs.shape[0]

    vmapped_reset = jax.vmap(env.reset, in_axes=(0, None))
    vmapped_step = jax.vmap(env.step, in_axes=(0, 0, 0, None))

    obs, env_state = vmapped_reset(rngs, env_params)

    if init_vitals is not None:
        h, f, d, e = init_vitals
        dtype = env_state.player_health.dtype
        env_state = env_state.replace(
            player_health=jnp.full((batch_size,), h, dtype=dtype),
            player_food=jnp.full((batch_size,), f, dtype=dtype),
            player_drink=jnp.full((batch_size,), d, dtype=dtype),
            player_energy=jnp.full((batch_size,), e, dtype=dtype),
        )
        obs = jax.vmap(env.get_obs)(env_state)
    done = jnp.zeros(batch_size, dtype=bool)
    hstate = ScannedRNN.initialize_carry(batch_size, config["LAYER_SIZE"])

    def _step(carry, _):
        env_state, obs, done, hstate, rngs = carry

        ac_in = (obs[jnp.newaxis, :], done[jnp.newaxis, :])
        hstate, pi, _ = network.apply(train_state.params, hstate, ac_in)

        # Per-env independent RNG splitting
        split_rngs = jax.vmap(lambda r: jax.random.split(r, 3))(rngs)
        rngs = split_rngs[:, 0]
        action_rngs = split_rngs[:, 1]
        step_rngs = split_rngs[:, 2]

        # Per-env independent action sampling
        logits = pi.logits.squeeze(0)
        action = jax.vmap(jax.random.categorical)(action_rngs, logits)

        obs_new, env_state_new, _, new_done, _ = vmapped_step(
            step_rngs, env_state, action, env_params
        )

        carry = (env_state_new, obs_new, new_done, hstate, rngs)
        return carry, (env_state, action, new_done)

    init_rngs = jax.random.split(rng, batch_size)
    init_carry = (env_state, obs, done, hstate, init_rngs)
    final_carry, (pre_states, all_actions, all_dones) = jax.lax.scan(
        _step, init_carry, None, max_steps
    )

    # Append final env state (state after last step)
    final_env_state = final_carry[0]
    all_states = jax.tree.map(
        lambda s, f: jnp.concatenate([s, f[jnp.newaxis]], axis=0),
        pre_states, final_env_state,
    )

    return all_states, all_actions, all_dones


def save_episode_from_batch(state_path, all_states, all_actions, j, num_actions, num_states):
    """Save a single episode extracted from batched trajectory data."""
    s = slice(None, num_states)
    a = slice(None, num_actions)

    np.savez_compressed(
        state_path,
        action=all_actions[a, j],
        map=all_states.map[s, j],
        mob_map=all_states.mob_map[s, j],
        player_position=all_states.player_position[s, j],
        player_direction=all_states.player_direction[s, j],
        player_health=all_states.player_health[s, j],
        player_food=all_states.player_food[s, j],
        player_drink=all_states.player_drink[s, j],
        player_energy=all_states.player_energy[s, j],
        is_sleeping=all_states.is_sleeping[s, j],
        player_recover=all_states.player_recover[s, j],
        player_hunger=all_states.player_hunger[s, j],
        player_thirst=all_states.player_thirst[s, j],
        player_fatigue=all_states.player_fatigue[s, j],
        inventory_wood=all_states.inventory.wood[s, j],
        inventory_stone=all_states.inventory.stone[s, j],
        inventory_coal=all_states.inventory.coal[s, j],
        inventory_iron=all_states.inventory.iron[s, j],
        inventory_diamond=all_states.inventory.diamond[s, j],
        inventory_sapling=all_states.inventory.sapling[s, j],
        inventory_wood_pickaxe=all_states.inventory.wood_pickaxe[s, j],
        inventory_stone_pickaxe=all_states.inventory.stone_pickaxe[s, j],
        inventory_iron_pickaxe=all_states.inventory.iron_pickaxe[s, j],
        inventory_wood_sword=all_states.inventory.wood_sword[s, j],
        inventory_stone_sword=all_states.inventory.stone_sword[s, j],
        inventory_iron_sword=all_states.inventory.iron_sword[s, j],
        zombies_position=all_states.zombies.position[s, j],
        zombies_health=all_states.zombies.health[s, j],
        zombies_mask=all_states.zombies.mask[s, j],
        zombies_attack_cooldown=all_states.zombies.attack_cooldown[s, j],
        cows_position=all_states.cows.position[s, j],
        cows_health=all_states.cows.health[s, j],
        cows_mask=all_states.cows.mask[s, j],
        cows_attack_cooldown=all_states.cows.attack_cooldown[s, j],
        skeletons_position=all_states.skeletons.position[s, j],
        skeletons_health=all_states.skeletons.health[s, j],
        skeletons_mask=all_states.skeletons.mask[s, j],
        skeletons_attack_cooldown=all_states.skeletons.attack_cooldown[s, j],
        arrows_position=all_states.arrows.position[s, j],
        arrows_health=all_states.arrows.health[s, j],
        arrows_mask=all_states.arrows.mask[s, j],
        arrows_attack_cooldown=all_states.arrows.attack_cooldown[s, j],
        arrow_directions=all_states.arrow_directions[s, j],
        growing_plants_positions=all_states.growing_plants_positions[s, j],
        growing_plants_age=all_states.growing_plants_age[s, j],
        growing_plants_mask=all_states.growing_plants_mask[s, j],
        light_level=all_states.light_level[s, j],
        achievements=all_states.achievements[s, j],
        state_rng=all_states.state_rng[s, j],
        timestep=all_states.timestep[s, j],
    )


def main(args):
    root_path = os.path.join(args.save_path, args.env_name)
    os.makedirs(root_path, exist_ok=True)
    state_path = os.path.join(root_path, "state")
    os.makedirs(state_path, exist_ok=True)

    with open(os.path.join(args.checkpoint_path, "config.yaml")) as f:
        raw_config = yaml.load(f, Loader=yaml.Loader)

        config = {}
        for key, value in raw_config.items():
            if isinstance(value, dict) and "value" in value:
                config[key] = value["value"]
    config["_TRAIN_NUM_ENVS"] = config.get("NUM_ENVS", 1)
    config["NUM_ENVS"] = 1
    config.pop("_wandb", None)

    for key in _SPAWN_PARAM_KEYS:
        cli_val = getattr(args, key)
        if cli_val is not None:
            config[key.upper()] = cli_val

    # Initialize environment
    env = make_craftax_env_from_name(args.env_name, False)
    env_params = _apply_env_param_overrides(env.default_params, config)
    action_dim = env.action_space(env_params).n

    # Load policy
    network, train_state = load_policy(
        args.checkpoint_path, config, env, action_dim, seed=args.seed
    )

    batch_size = args.batch_size
    max_steps = args.max_steps

    init_vitals = tuple(args.init_vitals) if args.init_vitals is not None else None

    # JIT-compile batched generation
    @jax.jit
    def _generate(rngs, rng):
        return generate_batch(
            network, train_state, env, env_params, config,
            rngs, max_steps, rng, init_vitals=init_vitals,
        )

    # Generate in batches
    num_batches = (args.n_episodes + batch_size - 1) // batch_size
    ep_idx = args.start_ep

    def save_batch(all_states, all_actions, all_dones, batch_n, start_ep_idx):
        """Save all episodes from a batch in parallel threads."""
        def _save_one(j):
            done_indices = np.where(all_dones[:, j])[0]
            if len(done_indices) > 0:
                t = done_indices[0]
                num_actions = t + 1
                num_states = t + 2
            else:
                num_actions = max_steps
                num_states = max_steps

            save_episode_from_batch(
                os.path.join(state_path, f"episode_{start_ep_idx + j:05d}.npz"),
                all_states, all_actions, j, num_actions, num_states,
            )

        with ThreadPoolExecutor(max_workers=min(8, batch_n)) as pool:
            list(pool.map(_save_one, range(batch_n)))

    pending_future = None
    save_executor = ThreadPoolExecutor(max_workers=1)

    for batch_i in tqdm(range(num_batches), desc="Generating batches"):
        remaining = args.n_episodes - batch_i * batch_size
        batch_n = min(batch_size, remaining)

        # Always use full batch_size for consistent JIT shapes; extra episodes are discarded
        reset_rngs, step_rng = make_batch_rngs(
            seed=args.seed,
            start_ep=args.start_ep,
            batch_i=batch_i,
            batch_size=batch_size,
        )

        all_states, all_actions, all_dones = _generate(reset_rngs, step_rng)

        # Transfer to CPU
        all_states, all_actions, all_dones = jax.device_get(
            (all_states, all_actions, all_dones)
        )

        # Wait for previous batch save before starting new one
        if pending_future is not None:
            pending_future.result()

        # Save in background while GPU generates next batch
        pending_future = save_executor.submit(
            save_batch, all_states, all_actions, all_dones, batch_n, ep_idx,
        )
        ep_idx += batch_n

    # Wait for last save
    if pending_future is not None:
        pending_future.result()
    save_executor.shutdown()


def main_cli(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--env_name", type=str, default="Craftax-Classic-Symbolic-v1")
    parser.add_argument(
        "--checkpoint_path",
        "--checkpoint",
        dest="checkpoint_path",
        type=str,
        required=True,
        help="Path to the trained policy checkpoint",
    )
    parser.add_argument(
        "--max_steps", type=int, default=10000, help="Maximum steps per trajectory"
    )
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--disable_jit", action="store_true")

    parser.add_argument(
        "--save_path", type=str, default="data/episodes"
    )
    parser.add_argument("--start_ep", type=int, default=0)
    parser.add_argument(
        "--n_episodes", type=int, default=20000,
        help="Number of trajectories to generate",
    )
    parser.add_argument(
        "--batch_size", type=int, default=64,
        help="Number of parallel environments for batched generation",
    )
    parser.add_argument(
        "--init_vitals", type=int, nargs=4, default=None,
        metavar=("HEALTH", "FOOD", "DRINK", "ENERGY"),
        help="Override initial player vitals (health food drink energy) at each episode reset",
    )
    parser.add_argument("--spawn_cow_chance", type=float, default=None)
    parser.add_argument("--spawn_zombie_base_chance", type=float, default=None)
    parser.add_argument("--spawn_zombie_night_chance", type=float, default=None)
    parser.add_argument("--spawn_skeleton_chance", type=float, default=None)

    args = parser.parse_args(argv)

    if args.disable_jit:
        print("[INFO] Disabling JIT")
        with jax.disable_jit():
            main(args)
    else:
        main(args)


if __name__ == "__main__":
    main_cli()
